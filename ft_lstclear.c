#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*head;
	t_list	*tmp;

	head = *lst;
	while (head != NULL)
	{
		del(head->content);
		tmp = head->next;
		free(head);
		head = tmp;
	}
	*lst = NULL;
}
